import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const code=fs.readFileSync('api/inventory-import.js','utf8');
const files=new Map(),calls=[];
let conflict=false, now='2026-10-13T15:23:00.000Z';
const fakeFetch=async(url,opts={})=>{
 const route=new URL(url).pathname.split('/repos/example/inventory-system/')[1];
 const method=opts.method||'GET',payload=opts.body?JSON.parse(opts.body):null;
 calls.push({route,method,payload});
 let response;
 if(method==='GET'&&route==='git/commits/HEAD_SHA')response={tree:{sha:'BASE_TREE'}};
 else if(method==='POST'&&route==='git/trees')response={sha:'NEW_TREE'};
 else if(method==='POST'&&route==='git/commits')response={sha:'NEW_COMMIT'};
 else if(method==='PATCH'&&route==='git/refs/heads/main'&&!conflict)response={object:{sha:'NEW_COMMIT'}};
 else if(method==='PATCH'&&route==='git/refs/heads/main'&&conflict)return{ok:false,status:422,json:async()=>({message:'Update is not a fast forward'})};
 else throw Error('Unexpected '+method+' '+route);
 return{ok:true,status:200,json:async()=>response};
};
const sandbox={require,module:{exports:{}},process:{env:{}},Buffer,Intl,fetch:fakeFetch,Date};
vm.runInNewContext(code+'\nthis.__atomic={saveInventoryWithVersion,riyadhDate,prepare};',sandbox);
const {saveInventoryWithVersion,riyadhDate,prepare}=sandbox.__atomic;
assert.equal(riyadhDate(new Date(now)),'2026-10-13 18:23','Timestamp must use Saudi local time');
for(const kind of ['jeddah','riyadh','pricing']){
 calls.length=0;
 const c={owner:'example',repo:'inventory-system',token:'DUMMY',branch:'main'};
 const saved=await saveInventoryWithVersion(c,'HEAD_SHA','data/'+kind+'.tsv','TEST_CONTENT\n');
 assert.equal(saved.sha,'NEW_COMMIT');
 assert.match(saved.lastUpdate,/^\d{4}-\d\d-\d\d \d\d:\d\d$/);
 const tree=calls.find(x=>x.route==='git/trees');
 assert.ok(tree&&tree.payload.base_tree==='BASE_TREE');
 assert.equal(tree.payload.tree.length,2,'Stock and version must be in one atomic Git tree');
 assert.equal(tree.payload.tree[0].path,'data/'+kind+'.tsv');
 assert.equal(tree.payload.tree[0].content,'TEST_CONTENT\n');
 assert.equal(tree.payload.tree[1].path,'data/version.json');
 const version=JSON.parse(tree.payload.tree[1].content);
 assert.equal(version.lastUpdate,saved.lastUpdate,'Version timestamp must match confirmed commit');
 assert.deepEqual(Array.from(calls.find(x=>x.route==='git/commits'&&x.method==='POST').payload.parents),['HEAD_SHA']);
 const patch=calls.find(x=>x.route==='git/refs/heads/main'&&x.method==='PATCH');
 assert.equal(patch.payload.sha,'NEW_COMMIT');
 assert.equal(patch.payload.force,false,'Never force-push over concurrent edits');
}
conflict=true;
await assert.rejects(saveInventoryWithVersion({owner:'example',repo:'inventory-system',token:'DUMMY',branch:'main'},'HEAD_SHA','data/jeddah.tsv','TEST\n'),e=>e.status===409&&/أعد المعاينة/.test(e.message));
const jed=fs.readFileSync('data/jeddah.tsv','utf8');
const initial=prepare('jeddah',jed,jed);
assert.equal(initial.content,jed);
assert.equal(initial.summary.changed,0);
console.log('V60_ATOMIC_VERSION_PASS: 3 datasets, Saudi timezone, 2-file tree, no force push, conflict and no-change guard');
