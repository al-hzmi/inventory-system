'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
require('../stocktake-branches.js');
const B=global.StocktakeBranches;
assert.equal(B.branchOf({warehouseKey:'jeddah'}),'jeddah');
assert.equal(B.branchOf({warehouse:'مستودع الرياض'}),'riyadh');
assert.equal(B.branchOf({testWarehouseKey:'riyadh'}),'riyadh');
assert.equal(B.branchOf({warehouse:'غير معروف'}),'');
const people=Array.from({length:8},(_,i)=>'employee_'+(i+1));
const admin='admin_mohanad';
let map={};
const j={campaignId:'j-annual',allowedEmployeeIds:[admin,...people.slice(0,4)],allowedEmployeeNames:['مهند','جدة 1','جدة 2','جدة 3','جدة 4']};
const r={campaignId:'r-annual',allowedEmployeeIds:[admin,...people.slice(4)],allowedEmployeeNames:['مهند','رياض 1','رياض 2','رياض 3','رياض 4']};
map.jeddah=B.assertNoCollision(map,'jeddah',j);
map.riyadh=B.assertNoCollision(map,'riyadh',r);
const control={...B.patchFor(map,'r-annual'),searchKeyboardMode:'numeric'};
assert.equal(control.enabled,true);
assert.equal(control.activeCampaignId,'r-annual');
assert.equal(control.allowedEmployeeIds.length,9,'eight employees plus one admin');
assert.deepEqual(Object.keys(B.activeMap(control)),['jeddah','riyadh']);
for(let i=0;i<8;i++){
 const account={employeeId:people[i],name:i<4?'جدة '+(i+1):'رياض '+(i-3),isAdmin:false};
 const assigned=B.available(control,account);
 assert.equal(assigned.length,1,'each employee must be routed to just one branch');
 assert.equal(assigned[0].branch,i<4?'jeddah':'riyadh');
 assert(B.isActive(control,assigned[0].campaignId,assigned[0].branch));
 assert(!B.isActive(control,assigned[0].campaignId,i<4?'riyadh':'jeddah'));
}
assert.equal(B.available(control,{isAdmin:true}).length,2);
assert.equal(B.available(control,{employeeId:'stranger',name:'مهند',isAdmin:false}).length,0,'admin name is not a worker credential');
assert.throws(()=>B.assertNoCollision(map,'jeddah',{campaignId:'another-jeddah',allowedEmployeeIds:[],allowedEmployeeNames:[]}),/ACTIVE_STOCKTAKE_SAME_BRANCH/);
assert.throws(()=>B.assertNoCollision(map,'riyadh',{campaignId:'r-annual',allowedEmployeeIds:[people[0]],allowedEmployeeNames:[]}),/STOCKTAKE_EMPLOYEE_BRANCH_OVERLAP/);
assert.throws(()=>B.assertNoCollision(map,'riyadh',{campaignId:'r-annual',allowedEmployeeIds:[],allowedEmployeeNames:['جدة 1']}),/STOCKTAKE_EMPLOYEE_BRANCH_OVERLAP/);
const afterClose={...map};delete afterClose.jeddah;
const stillRunning=B.patchFor(afterClose,control.activeCampaignId);
assert.equal(stillRunning.enabled,true,'closing Jeddah must never disable Riyadh');
assert.equal(stillRunning.activeCampaignId,'r-annual');
assert.equal(stillRunning.activeCampaigns.jeddah,null);
assert.equal(B.available(stillRunning,{employeeId:people[4],name:'رياض 1',isAdmin:false})[0].branch,'riyadh');
assert.equal(B.available(stillRunning,{employeeId:people[0],name:'جدة 1',isAdmin:false}).length,0);
const afterAll=B.patchFor({},'');
assert.equal(afterAll.enabled,false);
assert.equal(afterAll.activeCampaignId,'');
const legacy={enabled:true,activeCampaignId:'legacy-jeddah',accessMode:'selected',allowedEmployeeIds:['old-worker'],allowedEmployeeNames:[]};
assert.equal(B.available(legacy,{employeeId:'old-worker',name:'قديم',isAdmin:false})[0].campaignId,'legacy-jeddah');
assert(B.isActive(legacy,'legacy-jeddah','jeddah'));
assert.equal(B.isActive(legacy,'nope','jeddah'),false);
const read=f=>fs.readFileSync(f,'utf8');
const a=read('admin-stocktake.html'),e=read('stocktake.html'),sw=read('sw.js');
assert(a.includes('StocktakeBranch.patchFor(map,cp.id)'));
const reset=a.slice(a.indexOf('async function resetAllPreviousStocktakes()'),a.indexOf('async function auditAdmin('));
assert(reset.includes('.filter(c=>c.isTest||c.testMode)'),'test cleanup must never include real campaigns');
assert(!reset.includes('await control.set({enabled:false'),'test cleanup must never disable an active real stocktake');
assert(a.includes('StocktakeBranch.assertNoCollision(map,branch,next,norm)'));
assert(a.includes('StocktakeBranch.patchFor(map,control.activeCampaignId)'));
assert(a.includes("if(activeStocktakeCampaign(key))throw Error('ACTIVE_STOCKTAKE_SAME_BRANCH')"));
assert(!a.slice(a.indexOf('async function markReady()'),a.indexOf('async function syncAccessFrom(')).includes('syncAccess(false)'),'preparing Riyadh must not suspend active Jeddah');
assert(e.includes('StocktakeBranches.available(c,user,norm)'));
assert(e.includes('StocktakeBranches.isActive(control,entryCampaignId,StocktakeBranches.branchOf(campaign))'));
assert(e.includes("where('campaignId','==',chosen.campaignId)"),'employee subscription must be campaign-scoped');
assert(a.includes("warehouseKey:key"));
assert(e.includes('stocktake-branches.js?v=116.0'));
assert(a.includes('stocktake-branches.js?v=116.0'));
assert(sw.includes("'/stocktake-branches.js'"));
console.log('V116_DUAL_BRANCH_STOCKTAKE_PASS: independent Jeddah/Riyadh, 8 groups, atomic-control contracts, no cross-branch suspension');
