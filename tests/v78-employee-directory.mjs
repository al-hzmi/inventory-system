import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),Babel=require('@babel/standalone');
const html=fs.readFileSync(new URL('../admin-dashboard.html',import.meta.url),'utf8');
const source=html.match(/<script type="text\/babel">([\s\S]*?)<\/script>/)[1];
Babel.transform(source,{presets:['react'],filename:'admin-dashboard.jsx'});
const normalizeText=s=>String(s||'').toLowerCase().replace(/[أإآٱ]/g,'ا').replace(/ة/g,'ه').replace(/\s+/g,' ').trim();
const ctx=vm.createContext({normalizeText,employeeAliasVariants:value=>{const base=normalizeText(value);return base?[...new Set([base,base.replace(/\s+/g,'')])]:[]}});
const helper=source.slice(source.indexOf('function buildEmployeeDirectory('),source.indexOf('\nconst ',source.indexOf('function buildEmployeeDirectory(')));
vm.runInContext(helper+';globalThis.directory=buildEmployeeDirectory;',ctx);
const accounts=[{id:'khalid',canonicalName:'خالد الحزمي',aliases:['خالد','خالد الحزمي']},{id:'ezz',canonicalName:'عزالدين الإدريسي',aliases:['عز','عز الدين الإدريسي']},{id:'old-ezz',canonicalName:'عزالدين',status:'merged',mergedInto:'ezz'}];
const users=[{id:'u1',name:'خالد'},{id:'u2',name:'خالد الحزمي'},{id:'u3',name:'قديم',employeeId:'khalid'},{id:'u4',name:'عز',employeeId:'old-ezz'},{id:'u5',name:'نسيم الصلاحي'},{id:'u6',name:'نسيمالصلاحي'},{id:'u7',name:'خالد آخر'}];
const before=JSON.stringify({accounts,users});
const d=ctx.directory(users,accounts,[]);
assert.equal(d.rows.length,4,'legacy aliases + ID links collapse to one person; similar first name stays separate');
assert.equal(d.rows.find(x=>x.account?.id==='khalid').userRecords.length,3);
assert.equal(d.rows.find(x=>x.account?.id==='ezz').userRecords.length,1);
assert.equal(d.rows.find(x=>x.name==='نسيم الصلاحي').userRecords.length,2);
assert.equal(d.identity({repName:'خالد'}),d.identity({employeeId:'khalid'}),'historical orders resolve canonical owner');
assert.equal(d.identity({repName:'نسيم الصلاحي'}),d.identity({name:'نسيمالصلاحي'}),'unlinked legacy order history remains grouped');
assert.equal(d.identity({employeeId:'old-ezz'}),d.identity({employeeId:'ezz'}),'merged account history is retained');
assert.notEqual(d.identity({name:'خالد آخر'}),d.identity({name:'خالد'}),'no first-name-only merge');
assert.equal(JSON.stringify({accounts,users}),before,'grouping never alters stored records');
const conflicting=ctx.directory([{id:'u',name:'محمد'}],[{id:'a',canonicalName:'محمد الأول',aliases:['محمد']},{id:'b',canonicalName:'محمد الثاني',aliases:['محمد']}],[]);
assert.equal(conflicting.rows.find(x=>x.user)?.account,null,'ambiguous aliases cannot silently merge people');
assert.match(source,/defaultBranch,passwordPending/);
assert.match(source,/defaultBranch,accountEnabled/);
assert.match(source,/value="jeddah"/);assert.match(source,/value="riyadh"/);
console.log('PASS employee identity grouping, immutable history, alias collisions, branch form and JSX compilation');
const fallbackLine=source.match(/const needsIndexFallback=([^;]+);/)[1];
const shouldFallback=vm.runInNewContext('('+fallbackLine+')',{field:'timestamp'});
assert.equal(shouldFallback({code:'resource-exhausted',message:'Quota exceeded'}),false);
assert.equal(shouldFallback({code:'permission-denied'}),false);
assert.equal(shouldFallback({code:'unavailable'}),false);
assert.equal(shouldFallback({code:'failed-precondition',message:'The query requires an index'}),true);
assert.equal(vm.runInNewContext('('+fallbackLine+')',{field:undefined})({code:'failed-precondition'}),false);
console.log('PASS admin read failures do not issue duplicate quota/permission/network retries');
