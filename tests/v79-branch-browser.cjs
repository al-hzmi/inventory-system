const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {chromium,webkit}=require('playwright');
const browserType=process.env.BROWSER==='webkit'?webkit:chromium;
const fixture='رقم الصنف\tاسم الصنف\tالوحدة\tالكمية المتوفرة\tالشد\nARM_10004\tصنف موجود بالمستودع\tكرتون\t9\t60\nARM_10005\tصنف غير متوفر\tكرتون\t0\t36\nARM_10006\tصنف آخر\tقطعة\t7\t1\n';
(async()=>{
 const browser=await browserType.launch({headless:true,args:browserType===chromium?['--no-sandbox']:[]});
 const context=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block',acceptDownloads:true});
 await context.addInitScript(()=>{
   localStorage.setItem('inventory_user_name_v2','موظف الاختبار');
   localStorage.setItem('inventory_employee_id_v2','qa-branch-employee');
   localStorage.setItem('inventory_employee_auth_version_v2','2');
   localStorage.setItem('inventory_login_photo_proof_v2',JSON.stringify({role:'employee',employeeId:'qa-branch-employee',photoId:'qa-proof'}));
 });
 let online=true;
 await context.route('**/*',async route=>{
   const request=route.request(),url=new URL(request.url()),file=path.join(process.cwd(),decodeURI(url.pathname).replace(/^\//,''));
   if(url.pathname==='/data/jeddah.tsv'){if(!online)return route.abort();return route.fulfill({body:fixture,contentType:'text/tab-separated-values'})}
   if(url.hostname!=='localhost'||!fs.existsSync(file)||!fs.statSync(file).isFile())return route.abort();
   const ext=path.extname(file),mime=ext==='.html'?'text/html':ext==='.js'?'application/javascript':ext==='.css'?'text/css':'image/svg+xml';
   return route.fulfill({body:fs.readFileSync(file),contentType:mime});
 });
 const page=await context.newPage(),errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto('http://localhost/branch-stocktake.html');
 await page.locator('#branchName').fill('معرض جدة');
 await page.locator('#newForm button[type="submit"]').click();
 await page.waitForFunction(()=>document.querySelector('#sessionName')?.textContent==='معرض جدة');
 assert.match(await page.locator('#summary').innerText(),/لم تُفحص/);
 let report=await page.evaluate(()=>{const t=JSON.parse(localStorage.getItem('batco_branch_audit_v79_qa-branch-employee'));return t.sessions[0]});
 assert.equal(Object.keys(report.entries).length,0);
 await page.locator('[data-zero="ARM_10004"]').click();
 assert.match(await page.locator('#summary').innerText(),/غير موجودة بالفرع/);
 await page.locator('[data-filter="missing"]').click();
 assert.equal(await page.locator('.item').count(),1);
 assert.match(await page.locator('.item').innerText(),/ARM_10004/);
 await page.locator('[data-filter="all"]').click();
 await page.locator('[data-zero="ARM_10005"]').click();
 assert.equal(await page.locator('[data-filter="missing"]').click().then(()=>page.locator('.item').count()),1,'warehouse zero is not a branch-only missing item');
 await page.locator('[data-filter="all"]').click();
 await page.locator('input[data-qty="ARM_10004"]').fill('١٫٥');
 await page.locator('input[data-qty="ARM_10004"]').press('Tab');
 await page.waitForTimeout(420);
 assert.equal(await page.locator('[data-filter="missing"]').click().then(()=>page.locator('.item').count()),0,'counted quantity removes missing status');
 await page.locator('[data-filter="all"]').click();
 await page.locator('[data-zero="ARM_10004"]').click();
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#exportMissing').click();
 const dl=await downloadPromise;assert.match(dl.suggestedFilename(),/نواقص.*\.csv$/);
 const csv=fs.readFileSync(await dl.path(),'utf8');
 assert.match(csv,/ARM_10004/);
 assert.ok(!csv.includes('ARM_10005'));
 online=false;
 await page.reload();
 await page.waitForFunction(()=>document.querySelector('#sessionName')?.textContent==='معرض جدة');
 assert.equal(await page.locator('[data-filter="missing"]').click().then(()=>page.locator('.item').count()),1);
 page.on('dialog',dialog=>dialog.accept());
 await page.locator('[data-filter="all"]').click();
 await page.locator('#bulkAbsent').click();
 let afterBulk=await page.evaluate(()=>JSON.parse(localStorage.getItem('batco_branch_audit_v79_qa-branch-employee')).sessions[0]);
 assert.equal(Object.keys(afterBulk.entries).length,3,'bulk confirmation records pending SKU only');
 assert.equal(await page.locator('[data-filter="missing"]').click().then(()=>page.locator('.item').count()),2);
 await page.locator('#undoBulk').click();
 let afterUndo=await page.evaluate(()=>JSON.parse(localStorage.getItem('batco_branch_audit_v79_qa-branch-employee')).sessions[0]);
 assert.equal(Object.keys(afterUndo.entries).length,2,'undo preserves hand-counted items');
 assert.equal(await page.locator('.item').count(),1,'undo restores previous missing list');
 await page.locator('#switchSession').click();
 assert.equal(await page.locator('.historyButton').count(),1);
 assert.deepEqual(errors,[]);
 console.log('PASS v79 '+(process.env.BROWSER||'chromium')+': login, branch stocktake, verified missing, offline reopen, CSV and UI');
 await browser.close();
})().catch(error=>{console.error(error);process.exitCode=1});
