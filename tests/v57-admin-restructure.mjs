import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const read=p=>fs.readFileSync(p,'utf8');
const home=read('admin-home.html'),dashboard=read('admin-dashboard.html'),importPage=read('admin-inventory-import.html');
const nav=read('v46-admin-nav.js'),workspace=read('v57-admin-workspace.js'),importer=read('inventory-import-ui.js'),api=read('api/inventory-import.js'),css=read('v57-admin-refresh.css'),formCSS=read('v57-admin-import.css');
for(const [p,src] of [['nav',nav],['workspace',workspace],['importer',importer],['backend',api]])new vm.Script(src,{filename:p+'.js'});
assert.ok(home.includes('v57-admin-workspace.js'),'Executive workspace not loaded');
assert.ok(home.includes('v46-admin-nav.js'),'Navigation missing from executive home');
assert.ok(importPage.includes('v46-admin-nav.js')&&importPage.includes('v57-admin-import.css'),'Importer is not integrated with admin shell');
assert.ok(dashboard.includes('admin-inventory-import.html'),'Admin dashboard missing Excel import entry');
assert.ok(nav.includes('admin-inventory-import.html'),'Admin sidebar missing Excel link');
assert.ok(nav.includes("'stocktake','import','images'"),'Mobile More menu missing Excel link');
assert.ok(nav.includes('v57-admin-refresh.css?v=57.1'),'Admin styles not enabled');
assert.ok(workspace.includes('المخزون والمنتجات')&&workspace.includes('الموظفون والعملاء')&&workspace.includes('التحليل والرقابة'),'Workspace sections missing');
assert.ok(!nav.includes('let n=0,t=setInterval'),'Legacy forced module polling was not removed');
assert.ok(importer.includes(String.raw`/\.xlsx?$/i`),'Excel extension recognition incorrect');
assert.ok(importer.includes(String.raw`FS:'\t'`)&&importer.includes(String.raw`RS:'\n'`),'Excel TSV separators must be real escape sequences');
assert.ok(css.includes('@media(max-width:900px)')&&css.includes('@media(max-width:640px)'),'Responsive breakpoints missing');
assert.ok(formCSS.includes('#app textarea'),'Import form not responsive');
const files=new Set(fs.readdirSync('.'));
for(const m of workspace.matchAll(/'\.\/([a-z-]+\.html)(?:\?[^']*)?'/g))assert.ok(files.has(m[1]),'Missing action destination: '+m[1]);
const ctx={module:{exports:{}},Buffer,process:{env:{}},require,fetch:()=>{throw Error('no network')}};
vm.runInNewContext(api+'\nthis.__prepare=prepare;',ctx,{filename:'api/inventory-import.js'});
const p=ctx.__prepare;
const current='رقم الصنف\tاسم الصنف\tالوحدة\tالكمية المتوفرة\tالشد\nBA_1006\tحاجز باب 90\tكرتون\t3.5\t48\nBA_1007\tحاجز باب 100\tكرتون\t2\t48\n';
const update='رقم الصنف\tالكمية المتوفرة\nBA_1006\t5\n';
const changed=p('jeddah',update,current);
assert.equal(changed.summary.changed,1);
assert.ok(changed.content.includes('BA_1006\tحاجز باب 90\tكرتون\t5\t48'));
assert.ok(changed.content.includes('BA_1007\tحاجز باب 100\tكرتون\t2\t48'));
assert.throws(()=>p('jeddah','رقم الصنف\tالكمية المتوفرة\nBA_1006\t-2\n',current));
assert.throws(()=>p('jeddah','رقم الصنف\tالكمية المتوفرة\nBA_9999\t3\n',current));
const pricing='مخزون جدة\t\t\t\t\tمخزون الرياض\t\nرقم الصنف\tسعر البيع\t\t\t\tرقم الصنف\tسعر البيع\nBA_1006\t30\t\t\t\tBA_1007\t40\n';
assert.equal(p('pricing','رقم الصنف\tسعر البيع\nBA_1006\t42\n',pricing).summary.changed,1);
assert.equal(p('pricing','مخزون جدة\t\t\t\t\tمخزون الرياض\t\nرقم الصنف\tسعر البيع\t\t\t\tرقم الصنف\tسعر البيع\nBA_1006\t30\t\t\t\tBA_1007\t45\n',pricing).summary.changed,1);
console.log('V57_ADMIN_RESTRUCTURE_PASS: nav, all routes, responsive CSS, Excel parser, five import scenarios');
