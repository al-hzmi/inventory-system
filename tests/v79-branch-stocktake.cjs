/* V79: branch presence is independent of the central warehouse's quantities. */
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('branch-stocktake-core.js','utf8');
new vm.Script(source,{filename:'branch-stocktake-core.js'});
new vm.Script(fs.readFileSync('branch-stocktake.js','utf8'),{filename:'branch-stocktake.js'});
new vm.Script(fs.readFileSync('sw.js','utf8'),{filename:'sw.js'});
const context=vm.createContext({});
vm.runInContext(source,context);
const C=context.BatcoBranchCore;
assert.equal(C.quantity('٠'),0);
assert.equal(C.quantity('١٫٥'),1.5);
assert.equal(C.quantity('1,200.25'),1200.25);
assert.equal(Number.isNaN(C.quantity('1e4')),true);
assert.equal(Number.isNaN(C.quantity('-1')),true);
assert.equal(Number.isNaN(C.quantity('')),true);
const fixtures='رقم الصنف\tاسم الصنف\tالوحدة\tالكمية المتوفرة\tالشد\nARM_10004\tبرطمان أحمر\tكرتون\t9\t60\nARM_10005\tغير متوفر\tكرتون\t0\t36\nARM_10006\t=HYPERLINK(\\"https://evil\\")\tقطعة\t20\t1\n';
const items=C.inventory(fixtures);
assert.equal(items.length,3);
assert.equal(items[0].sku,'ARM_10004');
assert.equal(items[0].warehouseQty,9);
assert.throws(()=>C.inventory(fixtures+'ARM_10004\tنسخة ثانية\tقطعة\t3\t1\n'),/DUPLICATE_SKU/);
assert.throws(()=>C.inventory('رقم الصنف\tاسم الصنف\tالوحدة\tالكمية المتوفرة\nA\tname\tpcs\twrong\n'),/INVALID_WAREHOUSE_QTY/);
let r=C.report(items,{});
assert.equal(r.counts.pending,3);
assert.equal(r.counts.missing,0,'uninspected inventory never qualifies as a branch shortage');
r=C.report(items,{'ARM_10004':{qty:0},'ARM_10005':{qty:0},'ARM_10006':{qty:1.5}});
assert.equal(r.counts.checked,3);
assert.equal(r.counts.missing,1);
assert.equal(r.counts.present,1);
assert.equal(r.counts.bothEmpty,1);
assert.equal(r.missing[0].sku,'ARM_10004');
assert.equal(C.report(items,{'ARM_10004':{qty:3}}).counts.missing,0);
const csv=C.csv(r.rows,{branch:'فرع جدة',warehouse:'مستودع جدة'});
assert.match(csv,/^\uFEFF/);
assert.match(csv,/فرع جدة/);
assert.match(csv,/'=HYPERLINK/,'CSV formula injection must be escaped');
assert.match(csv,/غير موجود بالفرع/);
assert.match(csv,/0/);
assert.equal(C.inventory(fs.readFileSync('data/jeddah.tsv','utf8')).length>500,true,'production fixture must load');
const html=fs.readFileSync('branch-stocktake.html','utf8');
assert.match(html,/branch-stocktake-core\.js/);
assert.match(html,/data-filter="missing"/);
assert.match(html,/exportMissing/);
const shell=fs.readFileSync('admin-stocktake-shell.html','utf8');
const admin=fs.readFileSync('admin-stocktake.html','utf8');
assert.match(shell,/branch-stocktake\.html/);assert.match(admin,/branch-stocktake\.html/);
const sw=fs.readFileSync('sw.js','utf8'),nav=fs.readFileSync('batco-fast-nav.js','utf8');
assert.match(sw,/branch-stocktake\.html/);assert.match(sw,/branch-stocktake-core\.js/);
assert.match(sw,/branch-stocktake\.css/);assert.match(nav,/branch-stocktake\.html/);
console.log('PASS v79: local branch counts, pending != missing, explicit zero, decimal inputs, frozen inventory, CSV safety, navigation and offline assets');
