const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const src=fs.readFileSync('batco-scan-pro.js','utf8');
new vm.Script(src,{filename:'batco-scan-pro.js'});
const scope={window:{}};vm.runInNewContext(src,scope);
const S=scope.window.BatcoScanPro;
assert.equal(S.checksum('5469835259789'),true);
assert.equal(S.checksum('5469835205335'),true);
assert.equal(S.checksum('5469835259788'),false);
assert.equal(S.skuFromBarcode('5469835259789'),'AR_25978');
assert.equal(S.skuFromBarcode('5469835205335'),'AR_20533');
assert.equal(S.skuFromBarcode('9043261141960'),'9043261141960','unexpected supplier must not get partial SKU');
assert.equal(S.formats({CODE_128:1,EAN_13:2,QR_CODE:3}).length,3);
const roi=S.cameraOptions(true).qrbox(390,300);
assert.ok(roi.width>=375&&roi.height>=225);
assert.equal(S.cameraOptions(true).videoConstraints.width.ideal,1920);
assert.equal(S.cameraOptions(false).videoConstraints,undefined);
const items=[{id:'AR_25978',sku:'AR_25978'},{id:'AR_20533',sku:'AR_20533'},{id:'ARM_10004',sku:'ARM_10004'}];
assert.equal(S.lookup('5469835259789',items).item.id,'AR_25978');
assert.equal(S.lookup('9043261141960',items).matched,false);
assert.equal(S.lookup('5469835259788',items).matched,false);
assert.equal(S.lookup('ARM_10004',items).matched,true);
let clock=0,confirmed=[];
const gate=S.createVerifier({now:()=>clock,onConfirm:code=>confirmed.push(code)});
assert.equal(gate.push('5469835259788','zxing').reason,'checksum');
assert.equal(gate.push('5469835259789','zxing').accepted,false);
clock=90;assert.equal(gate.push('5469835259789','zxing').accepted,false);
clock=175;assert.equal(gate.push('5469835259789','zxing').accepted,true);
assert.equal(confirmed[0],'5469835259789');
clock=185;assert.equal(gate.push('5469835259789','quagga').accepted,false,'same barcode must not be recorded twice while held');
clock=240;assert.equal(gate.push('5469835205335','zxing').accepted,false);
clock=315;assert.equal(gate.push('5469835205335','quagga').accepted,true,'two independent matching engines can confirm faster');
assert.equal(confirmed[1],'5469835205335');
const store=fs.readFileSync('branch-presence.js','utf8'),stock=fs.readFileSync('stocktake.html','utf8'),index=fs.readFileSync('runtime/index-v37-source.txt','utf8'),sw=fs.readFileSync('sw.js','utf8');
assert.match(store,/scanVerifier\.push/);
assert.match(store,/slice\(0,12\)/,'one authenticated transaction must process multiple accepted codes');
assert.match(store,/const doc=await txn\.get\(sessionRef\)/);
assert.match(store,/for\(const item of chunk\)/);
assert.match(stock,/BatcoScanPro/);
assert.match(stock,/BranchBarcodeFallback\.create/);
assert.match(stock,/BranchScanAudio\.play/);
assert.match(index,/const BarcodeScannerModal = memo\(\(\{ onClose, onScan, items=\[\] \}\)/);
assert.match(index,/Pro\.lookup\(code,items/);
assert.match(index,/BranchBarcodeFallback\.create/);
assert.match(sw,/stocktake-shell-v89/);
assert.match(sw,/batco-scan-pro\.js/);
console.log('PASS V89: checksum, consensus, verified manufacturer EAN, shared scanners, atomic 12-SKU Firestore transaction and cached PWA');
