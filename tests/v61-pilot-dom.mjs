let events=0;w.addEventListener('batco61:favorites-changed',()=>events++);
w.dispatchEvent(new w.CustomEvent('batco61:favorite-toggle',{detail:{sku:'GALLERY_ONLY_001',warehouse:'jeddah',name:'منتج مباشر',unit:'قطعة',qty:2,pack:'12'}}));
