const layout='<main><div class="sticky"><div class="batco-search-card"><div class="batco-search-card-head">مساحة العمل</div><div class="batco-search-row"><input id="searchInput"></div><div id="batco-pilot-search-slot"></div></div></div><section id="original-results">البحث القديم محفوظ</section></main>';
function session(id='101049',name='موظف معتمد'){
 const dom=new JSDOM('<!doctype html><html lang="ar"><body>'+layout+'</body></html>',{url,runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window;
 w.localStorage.setItem('inventory_user_name_v2',name);
 w.localStorage.setItem('inventory_employee_id_v2',id);
 w.localStorage.setItem('inventory_employee_auth_version_v2','2');
 w.localStorage.setItem('inventory_login_photo_proof_v2',JSON.stringify({role:'employee',employeeId:id,photoId:'verified'}));
 w.localStorage.setItem('batco_pilot61_'+id+'_classic',JSON.stringify({hidden:true}));
 w.fetch=async path=>({ok:true,text:async()=>stock(path.includes('riyadh')?'riyadh':'jeddah')});
 w.eval(js);
 w.document.dispatchEvent(new w.Event('DOMContentLoaded'));
 return dom;
}
