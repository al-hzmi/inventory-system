const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const js=fs.readFileSync('branch-barcode-fallback.js','utf8');
const coreJS=fs.readFileSync('branch-presence-core.js','utf8');
new vm.Script(js);new vm.Script(coreJS);
const scope=vm.createContext({});
vm.runInContext(js,scope);vm.runInContext(coreJS,scope);
const Q=scope.BranchBarcodeFallback,C=scope.BranchPresenceCore;
const ean='5469835001128';
assert.equal(Q.checkDigit(ean),true,'EAN-13 from first user video must verify');
assert.equal(Q.accept(ean,'ean_13'),true);
assert.equal(Q.checkDigit('5469835001127'),false);
assert.equal(Q.accept('5469835001127','ean_13'),false);
assert.equal(Q.accept('ARM_10004','code_128'),true);
assert.equal(Q.accept('','code_128'),false);
assert.equal(Q.config('data:image/jpeg;base64,dummy').locator.halfSample,false);
assert.equal(Q.config('data:image/jpeg;base64,dummy').numOfWorkers,0);
assert.ok(Q.config('test').decoder.readers.includes('ean_reader'));
const products=[{sku:'ARM_0112',warehouseQty:3},{sku:'ARM_10004',warehouseQty:4},{sku:'ARM_21003',warehouseQty:0}];
assert.equal(C.resolveScan(ean,products).reason,'unlinked-ean','EAN cannot silently map to a 4-digit substring');
assert.equal(C.resolveScan(ean,products).item,null);
assert.equal(C.resolveScan('ARM_10004',products).item.sku,'ARM_10004');
assert.equal(C.resolve('10004',products).item.sku,'ARM_10004');
const explicit=C.inventory('رقم الصنف\tاسم الصنف\tالوحدة\tالكمية المتوفرة\tالشد\tباركود\nARM_10004\tكوب\tكرتون\t10\t20\t'+ean+'\n');
assert.equal(explicit.length,1);
assert.equal(explicit[0].barcodes[0],ean);
assert.equal(C.resolveScan(ean,explicit).item.sku,'ARM_10004','real mapped barcode must register correct SKU');
const page=fs.readFileSync('branch-presence.html','utf8'),worker=fs.readFileSync('branch-presence.js','utf8');
assert.match(page,/branch-barcode-fallback\.js/);
assert.match(page,/id="cameraDecoded"/);
assert.match(worker,/alternateDecoder=window\.BranchBarcodeFallback\.create/);
assert.match(worker,/تم التعرف على الباركود/);
assert.match(worker,/resolveScan/);
assert.match(fs.readFileSync('sw.js','utf8'),/stocktake-shell-v85/);
console.log('PASS V85: verified EAN from uploaded clip, independent Quagga decoder, safe SKU matching and explicit barcode metadata');
